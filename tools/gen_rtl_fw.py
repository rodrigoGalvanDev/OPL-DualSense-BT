#!/usr/bin/env python3
"""Generate modules/ds34bt/iop/rtl8761b_fw.h from rtl8761b_fw.bin + rtl8761b_config.bin.

Usage (from the repo root):
    python tools/gen_rtl_fw.py path/to/rtl8761b_fw.bin path/to/rtl8761b_config.bin
"""
import hashlib, sys

EXPECT = {
    "fw": "0b59a1f2422c006837c4b5e46b59d49bfdbca1defb958adbbc0d57ebdc19cc82",
    "cfg": "aa86a092ee58e96256331d5c28c199ceaadec434460e98e7dea20e411e1aa570",
}
OUTS = ["modules/ds34bt/iop/rtl8761b_fw.h", "modules/pademu/rtl8761b_fw.h"]  # menu module and in-game module


def array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    fw = open(sys.argv[1], "rb").read()
    cfg = open(sys.argv[2], "rb").read()
    if not fw.startswith(b"Realtech"):
        sys.exit("rtl8761b_fw.bin: missing 'Realtech' signature")
    for k, d in (("fw", fw), ("cfg", cfg)):
        if hashlib.sha256(d).hexdigest() != EXPECT[k]:
            print("WARNING: sha256 of %s differs from the one this loader was written against" % k)
    text = "/* generated by tools/gen_rtl_fw.py - Realtek RTL8761B firmware */\n#ifndef _RTL8761B_FW_H_\n#define _RTL8761B_FW_H_\n\n"
    text += array("rtl8761b_fw", fw)
    text += "static const unsigned int rtl8761b_fw_size = %d;\n\n" % len(fw)
    text += array("rtl8761b_config", cfg)
    text += "static const unsigned int rtl8761b_config_size = %d;\n\n#endif\n" % len(cfg)
    for out in OUTS:
        with open(out, "w") as f:
            f.write(text)
        print("wrote", out)

main()
